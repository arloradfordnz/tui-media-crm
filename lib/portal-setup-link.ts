import type { SupabaseClient } from '@supabase/supabase-js'
import { sendClientAccountSetupEmail, sendClientPasswordResetEmail, sendMarketerAccountSetupEmail } from '@/lib/email'

const APP_URL = process.env.NEXT_PUBLIC_APP_URL || 'https://dashboard.tuimedia.nz'

/**
 * Email a client a link that lets them choose a password.
 *
 * ── Why the link is ours and not Supabase's ────────────────────────────────
 * generateLink() hands back an `action_link` on supabase.co. Sending that is
 * what broke account setup, twice over:
 *
 *  1. Supabase only redirects to URLs on the project's allow-list and silently
 *     falls back to the Site URL otherwise — which was `http://localhost:3000`.
 *  2. Even with the allow-list right, a link generated by the admin API uses
 *     the implicit flow, so the session arrives in the URL `#hash`. A route
 *     handler never sees a hash, so the old callback always saw "no code" and
 *     bounced the client to "That link was incomplete".
 *
 * So the email carries only the hashed token, on our own domain, and
 * /portal/setup exchanges it with verifyOtp() — which needs no redirect and no
 * allow-list. The exchange happens when the client SUBMITS their password, not
 * when the page loads, because mail scanners (Outlook Safe Links, Gmail's
 * prefetch) open every link in an email and would otherwise burn the
 * single-use token before the client ever clicks it.
 */
export async function emailPortalPasswordLink(
  admin: SupabaseClient,
  {
    email,
    name,
    clientId,
    kind,
    audience = 'client',
  }: {
    email: string
    name: string
    /** Absent for a marketer, who belongs to no client. */
    clientId?: string
    kind: 'setup' | 'reset'
    audience?: 'client' | 'marketer'
  },
): Promise<{ ok: true } | { ok: false; error: string }> {
  // A recovery link, not an invite link: invite links are refused for users
  // that already exist, and a re-send or a reset is exactly that.
  const { data: link, error } = await admin.auth.admin.generateLink({ type: 'recovery', email })
  const hashed = link?.properties?.hashed_token
  if (error || !hashed) return { ok: false, error: error?.message ?? 'Could not generate the link.' }

  const params = new URLSearchParams({ token: hashed })
  if (kind === 'reset') params.set('k', 'reset')
  const url = `${APP_URL}/portal/setup?${params}`

  try {
    if (audience === 'marketer') {
      await sendMarketerAccountSetupEmail({ to: email, name, setupUrl: url, reset: kind === 'reset' })
    } else {
      const send = kind === 'setup' ? sendClientAccountSetupEmail : sendClientPasswordResetEmail
      await send({ to: email, clientName: name, setupUrl: url, clientId })
    }
  } catch (err) {
    return { ok: false, error: err instanceof Error ? err.message : 'Could not send the email.' }
  }
  return { ok: true }
}
